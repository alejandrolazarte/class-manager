import { nodeFileSystem } from "@/testing/nodeFileSystem";
import { createWebExport, readExportedFile } from "../createWebExport";

const { relocateNodeModulesAssets } = jest.requireActual("../../relocateNodeModulesAssets.js");

const bundlePath = "_expo/static/js/web/entry.js";
const bundleContent = 'const logo = "/assets/assets/logo.png";';

describe("When web export has no node_modules assets", () => {
  let outputDirectory: string;

  beforeEach(() => {
    outputDirectory = createWebExport({ [bundlePath]: bundleContent });
  });

  afterEach(() => {
    nodeFileSystem.rmSync(outputDirectory, { recursive: true, force: true });
  });

  it("Then files are unchanged", () => {
    relocateNodeModulesAssets(outputDirectory);

    expect(readExportedFile(outputDirectory, bundlePath)).toBe(bundleContent);
  });
});
