import { nodeFileSystem, nodePath } from "@/testing/nodeFileSystem";
import { createWebExport, readExportedFile } from "../createWebExport";

const { relocateNodeModulesAssets } = jest.requireActual("../../relocateNodeModulesAssets.js");

const fontPath = "@expo/vector-icons/Fonts/Ionicons.b4eb.ttf";
const bundlePath = "_expo/static/js/web/entry.js";

describe("When web export has node_modules assets", () => {
  let outputDirectory: string;

  beforeEach(() => {
    outputDirectory = createWebExport({
      [`assets/node_modules/${fontPath}`]: "font",
      [bundlePath]: `const font = "/assets/node_modules/${fontPath}";`,
    });
  });

  afterEach(() => {
    nodeFileSystem.rmSync(outputDirectory, { recursive: true, force: true });
  });

  it("Then they are served from vendor", () => {
    relocateNodeModulesAssets(outputDirectory);

    expect(readExportedFile(outputDirectory, bundlePath)).toBe(
      `const font = "/assets/vendor/${fontPath}";`,
    );
    expect(readExportedFile(outputDirectory, `assets/vendor/${fontPath}`)).toBe("font");
    expect(nodeFileSystem.existsSync(nodePath.join(outputDirectory, "assets/node_modules"))).toBe(
      false,
    );
  });
});
